#Variables
'''A variable is simply a name that refer to a value.
Python variables are dynamically typed.'''
#Examples
name = "Chetan"
height = 180.5
is_student = True

print(name)
print(height)
print(is_student)

#Type checking
print(type(name))
print(type(height))
print(type(is_student))

#Type conversion
age = "22"
age_conversion = int(age)

print(age_conversion + 3)
